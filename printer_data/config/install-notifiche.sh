#!/usr/bin/env bash
# VzBot - installazione delle notifiche push sul Raspberry (versione 1.0)
#
# Uso:   bash install-notifiche.sh            (cerca da solo la chiave di Firebase accanto a questo file)
#        bash install-notifiche.sh /percorso/della-chiave.json
#
# Cosa fa (niente da scaricare, niente pip, nessuna modifica a Klipper, Moonraker o al Brain):
#   1. controlla che Python 3 ci sia
#   2. mette il programma e la tua chiave Firebase in ~/vzbot-notifier (chiave: solo tu puoi leggerla)
#   3. scrive la configurazione ~/vzbot-notifier/notifier.json (solo se non c'e' gia')
#   4. crea e avvia il servizio "vzbot-notifier", che parte da solo a ogni accensione
#   5. controlla che tutto funzioni
# Si puo' rilanciare quando si vuole: aggiorna il programma e non tocca la configurazione.

set -u

TOPIC="vzbot-pp3zt27qxb49fw3fsbvv"
PAYLOAD_SHA256="f1f66cb973740e9515a28001492f4ac77308b2f5081f60b5aef3080bff73d85d"
SERVICE="vzbot-notifier"
TARGET="${VZBOT_NOTIFIER_DIR:-$HOME/vzbot-notifier}"
SELF="${BASH_SOURCE[0]}"
HERE="$(cd "$(dirname "$SELF")" && pwd)"
SELF="$HERE/$(basename "$SELF")"

say()  { printf '%s\n' "$*"; }
step() { printf '\n== %s\n' "$*"; }
good() { printf '   OK    %s\n' "$*"; }
warn() { printf '   AVVISO %s\n' "$*"; }
stop() { printf '\n   ERRORE %s\n\n' "$*"; exit 1; }

say "VzBot - installazione delle notifiche sul telefono"

# --- 1. Python ---------------------------------------------------------------------------------------------------
step "1/5  Controllo Python"
PYTHON="$(command -v python3 || true)"
[ -n "$PYTHON" ] || stop "Python 3 non e' installato. Installalo con:  sudo apt install -y python3"
"$PYTHON" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 7) else 1)' || stop "Serve Python 3.7 o piu' recente (qui c'e' $("$PYTHON" --version 2>&1))."
good "$("$PYTHON" --version 2>&1)"

# --- 2. la chiave di Firebase --------------------------------------------------------------------------------------
step "2/5  Cerco la chiave di Firebase"
is_key() {  # 0 se il file e' una chiave di account di servizio
  [ -f "$1" ] && "$PYTHON" - "$1" <<'PY' >/dev/null 2>&1
import json, sys
d = json.load(open(sys.argv[1], encoding="utf-8"))
assert d.get("type") == "service_account" and d.get("private_key") and d.get("client_email") and d.get("project_id")
PY
}
KEY=""
if [ $# -ge 1 ]; then
  [ -f "$1" ] || stop "Il file indicato non esiste: $1"
  KEY="$1"
else
  for candidate in "$HERE"/service-account.json "$HERE"/*adminsdk*.json "$HERE"/*.json "$TARGET"/service-account.json; do
    [ -f "$candidate" ] || continue
    case "$(basename "$candidate")" in notifier.json|google-services.json) continue;; esac
    if is_key "$candidate"; then KEY="$candidate"; break; fi
  done
fi
if [ -z "$KEY" ]; then
  if [ -f "$HERE/google-services.json" ]; then
    warn "In $HERE c'e' google-services.json: quello serve per l'APP, non per il Raspberry."
  fi
  stop "Non trovo la chiave di Firebase. Carica nella stessa cartella di questo file il file .json scaricato da
          Firebase (Impostazioni progetto -> Account di servizio -> Genera nuova chiave privata) e rilancia."
fi
is_key "$KEY" || stop "$KEY non e' una chiave di account di servizio di Firebase (deve contenere \"type\": \"service_account\")."
PROJECT="$("$PYTHON" -c 'import json,sys; print(json.load(open(sys.argv[1], encoding="utf-8"))["project_id"])' "$KEY")"
good "Chiave trovata: $(basename "$KEY")  (progetto Firebase: $PROJECT)"

# --- 3. i file nella cartella definitiva -----------------------------------------------------------------------------
step "3/5  Copio i file in $TARGET"
mkdir -p "$TARGET" || stop "Non riesco a creare la cartella $TARGET"
chmod 700 "$TARGET"

START="$(awk '/^__PAYLOAD_BELOW__$/ { print NR + 1; exit }' "$SELF")"
[ -n "$START" ] || stop "Questo file e' incompleto (manca il programma). Riscaricalo e ricaricalo sul Raspberry."
tail -n +"$START" "$SELF" | tr -d '\r' | base64 -d > "$TARGET/vzbot_notifier.py.new" 2>/dev/null || stop "Il programma contenuto in questo file e' danneggiato. Riscaricalo e ricaricalo."
GOT="$(sha256sum "$TARGET/vzbot_notifier.py.new" | cut -d' ' -f1)"
[ "$GOT" = "$PAYLOAD_SHA256" ] || { rm -f "$TARGET/vzbot_notifier.py.new"; stop "Il programma contenuto in questo file e' danneggiato (impronta diversa). Riscaricalo e ricaricalo."; }
"$PYTHON" -m py_compile "$TARGET/vzbot_notifier.py.new" || stop "Il programma non e' valido per questo Python."
rm -rf "$TARGET/__pycache__"
mv -f "$TARGET/vzbot_notifier.py.new" "$TARGET/vzbot_notifier.py"
chmod 755 "$TARGET/vzbot_notifier.py"
good "Programma: $TARGET/vzbot_notifier.py"

if [ "$(readlink -f "$KEY")" != "$(readlink -f "$TARGET/service-account.json")" ]; then
  cp "$KEY" "$TARGET/service-account.json" || stop "Non riesco a copiare la chiave."
  chmod 600 "$TARGET/service-account.json"
  # la chiave e' una password: non deve restare nella cartella di configurazione, dove la vedrebbe chiunque apra la dashboard
  rm -f "$KEY" && good "Chiave spostata in $TARGET/service-account.json (la copia originale e' stata cancellata)"
else
  chmod 600 "$TARGET/service-account.json"
  good "Chiave gia' al suo posto"
fi

if [ -f "$TARGET/notifier.json" ]; then
  good "Configurazione gia' presente: la lascio com'e' ($TARGET/notifier.json)"
else
  cat > "$TARGET/notifier.json" <<CONF
{
  "_nota": "Se cambi qualcosa qui, poi esegui:  vzbot-notifiche riavvia",
  "service_account_file": "service-account.json",
  "topic": "$TOPIC",
  "title": "VzBot",
  "moonraker_url": "http://127.0.0.1:7125",
  "brain_url": "http://127.0.0.1:8085",
  "events": {
    "error": true,
    "complete": true,
    "cancelled": true,
    "paused": true,
    "runout": true,
    "ai_pause": true,
    "ai_cancel": true
  },
  "messages": {
    "error": "Stampante in errore! Effettuare riavvio.",
    "complete": "Stampa completata!",
    "cancelled": "Stampa interrotta!",
    "paused": "Stampante in pausa!",
    "runout": "Filamento esaurito, effettuare cambio bobina!",
    "ai_pause": "Difetti di stampa rilevati, verificare e mettere in pausa la stampa!",
    "ai_cancel": "Difetti gravi di stampa rilevati, verificare e interrompere la stampa"
  }
}
CONF
  chmod 600 "$TARGET/notifier.json"
  good "Configurazione scritta: $TARGET/notifier.json"
fi

# il comando corto "vzbot-notifiche"
cat > "$TARGET/vzbot-notifiche" <<'TOOL'
#!/usr/bin/env bash
# Comandi per le notifiche di VzBot:   vzbot-notifiche prova | controlla | stato | log | riavvia | disinstalla
DIR="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"
SERVICE="vzbot-notifier"
run() { python3 "$DIR/vzbot_notifier.py" --config "$DIR/notifier.json" "$@"; }
case "${1:-aiuto}" in
  prova)      run --test ;;
  controlla)  run --check ;;
  stato)      systemctl status "$SERVICE" --no-pager -l 2>&1 | head -n 25 ;;
  log)        journalctl -u "$SERVICE" -n 60 --no-pager 2>&1 || sudo journalctl -u "$SERVICE" -n 60 --no-pager ;;
  riavvia)    sudo systemctl restart "$SERVICE" && echo "Riavviato." ;;
  disinstalla)
    sudo systemctl disable --now "$SERVICE" 2>/dev/null
    sudo rm -f "/etc/systemd/system/$SERVICE.service" /usr/local/bin/vzbot-notifiche
    sudo systemctl daemon-reload
    echo "Servizio rimosso. I file sono ancora in $DIR: per cancellarli del tutto scrivi:  rm -r $DIR" ;;
  *) cat <<'HELP'
vzbot-notifiche prova        manda una notifica di prova al telefono
vzbot-notifiche controlla    controlla chiave, internet, Moonraker e Brain
vzbot-notifiche stato        dice se il servizio e' acceso
vzbot-notifiche log          mostra le ultime righe del registro (cosa e' stato inviato e gli eventuali errori)
vzbot-notifiche riavvia      rilegge notifier.json
vzbot-notifiche disinstalla  toglie il servizio
HELP
  ;;
esac
TOOL
chmod 755 "$TARGET/vzbot-notifiche"
if sudo ln -sf "$TARGET/vzbot-notifiche" /usr/local/bin/vzbot-notifiche 2>/dev/null; then
  good "Comando corto: vzbot-notifiche"
else
  warn "Non ho potuto creare il comando corto; usa  $TARGET/vzbot-notifiche"
fi

# --- 4. il servizio --------------------------------------------------------------------------------------------------
step "4/5  Servizio che parte da solo a ogni accensione"
if command -v systemctl >/dev/null 2>&1; then
  UNIT="[Unit]
Description=VzBot - notifiche push sul telefono
After=network-online.target moonraker.service
Wants=network-online.target

[Service]
Type=simple
User=$(id -un)
WorkingDirectory=$TARGET
Environment=PYTHONUNBUFFERED=1
ExecStart=$PYTHON $TARGET/vzbot_notifier.py --config $TARGET/notifier.json
Restart=always
RestartSec=10
Nice=10

[Install]
WantedBy=multi-user.target
"
  if printf '%s' "$UNIT" | sudo tee "/etc/systemd/system/$SERVICE.service" >/dev/null \
     && sudo systemctl daemon-reload && sudo systemctl enable "$SERVICE" >/dev/null 2>&1 && sudo systemctl restart "$SERVICE"; then
    good "Servizio $SERVICE attivo e abilitato all'avvio"
  else
    stop "Non sono riuscito a creare/avviare il servizio (serve sudo). Il programma e' comunque in $TARGET."
  fi
else
  warn "systemctl non c'e': il servizio non e' stato creato. Per provare a mano:  python3 $TARGET/vzbot_notifier.py"
fi

# --- 5. controllo -----------------------------------------------------------------------------------------------------
step "5/5  Controllo finale"
"$PYTHON" "$TARGET/vzbot_notifier.py" --config "$TARGET/notifier.json" --check
CHECK=$?
echo
if [ "$CHECK" -eq 0 ]; then
  say "Fatto! Sul Raspberry e' tutto pronto."
  say "Quando l'app e' installata sul telefono, prova con:   vzbot-notifiche prova"
else
  say "L'installazione e' finita, ma il controllo ha trovato qualcosa da sistemare (vedi sopra)."
  say "Sistemato il problema, riscrivi:   vzbot-notifiche controlla"
fi
say "Altri comandi:  vzbot-notifiche aiuto"
exit "$CHECK"

